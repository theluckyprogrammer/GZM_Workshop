using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Spectree.Generator;

// C# source of one test file: a normal xUnit class with [Fact(DisplayName = "Reguła N: sentence")] per rule
// and traits Capability and Rule. The body runs the [Step] method bound to that sentence, so a rule without a
// step is a red test with the message "Brak definicji kroku…".
public static class TestSource
{
    private const int MaxNameWords = 8;
    private const string Namespace = "GzmApp.Specs.Spec";

    // The marker of files this tool owns; only such files are ever deleted as stale.
    public static bool IsGenerated(string firstLine) => firstLine.Contains("<auto-generated by Spectree />", StringComparison.Ordinal);

    // Returns the file name (without extension) and the file content.
    public static (string Name, string Code) Emit(CapabilityFile file)
    {
        if (file?.Capability is null)
            throw new ArgumentException("Plik specyfikacji bez 'capability'.", nameof(file));

        var className = ClassName(file.Capability!);
        var code = new StringBuilder()
            .AppendLine("// <auto-generated by Spectree />")
            .AppendLine("// Testy tego kroku powstają ze specyfikacji (scenarios/sNN/spec/*.md) przy każdej kompilacji.")
            .AppendLine("// Nie edytuj tego pliku – zmiany znikną przy kolejnym buildzie. O zachowanie reguł dbasz")
            .AppendLine("// w kodzie aplikacji i w metodach z [Step(\"…\")] w tests/GzmApp.Specs/Steps/.")
            .AppendLine("#pragma warning disable")
            .AppendLine($"namespace {Namespace};")
            .AppendLine()
            .AppendLine($"[global::Xunit.Trait(\"Capability\", {Literal(file.Capability!)})]")
            .AppendLine($"public sealed class {className}")
            .AppendLine("{");
        foreach (var rule in file.Rules)
            AppendTest(code, className, file.RuleLabel, rule);
        return (className, code.AppendLine("}").ToString());
    }

    // "s02-002-szukaj-rekordow" → "S02_002_szukaj_rekordow".
    public static string ClassName(string capability) =>
        Capitalize(Identifier(capability ?? throw new ArgumentNullException(nameof(capability)), int.MaxValue));

    private static void AppendTest(StringBuilder code, string className, string label, Rule rule) =>
        code.AppendLine($"    [global::Xunit.Fact(DisplayName = {Literal($"{label} {rule.Number}: {rule.Sentence}")})]")
            .AppendLine($"    [global::Xunit.Trait(\"Rule\", \"{rule.Number}\")]")
            .AppendLine($"    public async global::System.Threading.Tasks.Task {label.Replace("ł", "l")}{rule.Number:00}_{Identifier(rule.Sentence, MaxNameWords)}()")
            .AppendLine("    {")
            .AppendLine($"        await global::Spectree.StepRegistry.RunAsync(typeof({className}).Assembly, {Literal(rule.Sentence)});")
            .AppendLine("    }")
            .AppendLine();

    // Letters and digits of the first words, joined with "_".
    private static string Identifier(string text, int words)
    {
        var parts = text.Split(new[] { ' ', '-', '/', '.', ',', ':', '(', ')' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(w => new string(w.Where(char.IsLetterOrDigit).ToArray()))
            .Where(w => w.Length > 0)
            .Take(words)
            .ToList();
        return parts.Count == 0 ? "Zdanie" : string.Join("_", parts);
    }

    private static string Capitalize(string name) => char.ToUpperInvariant(name[0]) + name.Substring(1);

    private static string Literal(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
